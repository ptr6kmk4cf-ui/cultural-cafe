export type UiKey = keyof typeof UI;
export type UiVars = Record<string, string | number>;
export type UiPack = Partial<Record<UiKey, string>>;

function fill(template: string, vars?: UiVars) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => (vars[key] == null ? '' : String(vars[key])));
}

/** One language pack. The report box stays in English because the server only accepts those reason words. */
export function uiFrom(pack: UiPack | undefined, key: UiKey, vars?: UiVars) {
  const translated = key === 'reportReason' ? undefined : pack?.[key];
  return fill(translated || UI[key], vars);
}
